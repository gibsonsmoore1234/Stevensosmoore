// Writes public/env.js with the PUBLIC Supabase settings the browser needs.
// Runs on Vercel (buildCommand) and locally via `npm run dev`.
// Reads the variable names set by the Vercel ↔ Supabase integration, or a
// local .env.local file. Refuses to publish a secret/service-role key.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function loadDotenv(file) {
  const path = join(root, file);
  if (!existsSync(path)) return;
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/);
    if (!m || m[1] in process.env) continue;
    process.env[m[1]] = m[2].trim().replace(/^(['"])(.*)\1$/, "$2");
  }
}
loadDotenv(".env.local");
loadDotenv(".env");

const pick = (...names) => {
  for (const n of names) {
    const v = process.env[n]?.trim();
    if (v) return { name: n, value: v };
  }
  return { name: null, value: "" };
};

const url = pick("SUPABASE_URL", "NEXT_PUBLIC_SUPABASE_URL", "VITE_SUPABASE_URL", "PUBLIC_SUPABASE_URL");
const key = pick(
  "SUPABASE_ANON_KEY",
  "NEXT_PUBLIC_SUPABASE_ANON_KEY",
  "SUPABASE_PUBLISHABLE_KEY",
  "NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY",
  "VITE_SUPABASE_ANON_KEY",
  "PUBLIC_SUPABASE_ANON_KEY",
);

function isSecretKey(k) {
  if (k.startsWith("sb_secret_")) return true;
  const parts = k.split(".");
  if (parts.length !== 3) return false;
  try {
    return JSON.parse(Buffer.from(parts[1], "base64url").toString("utf8")).role === "service_role";
  } catch {
    return false;
  }
}

if (key.value && isSecretKey(key.value)) {
  console.error(
    `\n✖ ${key.name} holds a Supabase SECRET (service_role) key. It must never be sent to browsers.\n` +
      `  Use the anon / publishable key instead (Supabase → Project Settings → API Keys).\n`,
  );
  process.exit(1);
}

let supabaseUrl = "";
if (url.value) {
  try {
    const u = new URL(url.value);
    if (u.protocol !== "https:" && u.hostname !== "localhost" && u.hostname !== "127.0.0.1") throw new Error("must be https");
    supabaseUrl = u.origin;
  } catch (err) {
    console.error(`\n✖ ${url.name} is not a valid URL (${err.message}): ${url.value}\n`);
    process.exit(1);
  }
}

const env = { SUPABASE_URL: supabaseUrl, SUPABASE_ANON_KEY: key.value };
writeFileSync(
  join(root, "public", "env.js"),
  `// Generated by scripts/build.mjs — do not edit or commit.\nwindow.__ENV__ = ${JSON.stringify(env)};\n`,
);

if (env.SUPABASE_URL && env.SUPABASE_ANON_KEY) {
  console.log(`✔ Supabase connected (${url.name}, ${key.name}) → ${env.SUPABASE_URL}`);
} else {
  console.warn(
    "⚠ Supabase env vars not found — the petition will run in local preview mode (signatures stay in your browser).\n" +
      "  Set SUPABASE_URL and SUPABASE_ANON_KEY (or the NEXT_PUBLIC_* names from the Vercel integration).",
  );
}
